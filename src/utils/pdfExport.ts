import { jsPDF } from 'jspdf';
import { AppLanguage, QaMessage, QuizQuestion, SummaryResult } from '../types.ts';

function containsNonAscii(text: string): boolean {
  return /[^\x00-\x7F]/.test(text);
}

function cleanPlainText(text: string): string {
  return (text || '')
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/\*([^*]+)\*/g, '$1')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/^#{1,6}\s+/gm, '');
}

async function renderUnicodeLinesToPdf(
  docTitle: string,
  subtitle: string,
  sections: { heading: string; lines: string[] }[],
  outputFilename: string
) {
  if (typeof document !== 'undefined' && document.fonts?.ready) {
    await document.fonts.ready;
  }
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  const scale = 2;
  const canvasW = 794 * scale;
  const canvasH = 1123 * scale;
  const margin = 56 * scale;
  const maxWidth = canvasW - margin * 2;

  const createPageCanvas = (pageNum: number) => {
    const canvas = document.createElement('canvas');
    canvas.width = canvasW;
    canvas.height = canvasH;
    const ctx = canvas.getContext('2d')!;
    ctx.fillStyle = '#FFFFFF';
    ctx.fillRect(0, 0, canvasW, canvasH);

    // Header band
    ctx.fillStyle = '#172554';
    ctx.fillRect(0, 0, canvasW, 74 * scale);

    ctx.fillStyle = '#FFFFFF';
    ctx.font = `700 ${18 * scale}px "Plus Jakarta Sans", "Noto Sans Tamil", sans-serif`;
    ctx.fillText('JOSH PDF', margin, 34 * scale);

    ctx.fillStyle = '#93C5FD';
    ctx.font = `500 ${10 * scale}px "DM Sans", "Noto Sans Tamil", sans-serif`;
    ctx.fillText('Upload. Understand. Learn Faster.  ·  Free AI-Powered PDF Summarizer', margin, 54 * scale);

    // Footer
    ctx.fillStyle = '#64748B';
    ctx.font = `400 ${9.5 * scale}px "DM Sans", "Noto Sans Tamil", sans-serif`;
    ctx.fillText(
      `Generated by JOSH PDF  ·  Page ${pageNum}`,
      margin,
      canvasH - 28 * scale
    );

    return { canvas, ctx };
  };

  let pageNum = 1;
  let { canvas, ctx } = createPageCanvas(pageNum);
  let y = 110 * scale;

  const nextPage = () => {
    doc.addImage(canvas.toDataURL('image/png'), 'PNG', 0, 0, pageWidth, pageHeight);
    doc.addPage();
    pageNum += 1;
    const next = createPageCanvas(pageNum);
    canvas = next.canvas;
    ctx = next.ctx;
    y = 104 * scale;
  };

  const drawWrapped = (
    text: string,
    font: string,
    color: string,
    lineHeight: number
  ) => {
    ctx.font = font;
    ctx.fillStyle = color;
    const paragraphs = cleanPlainText(text).split(/\r?\n/);
    for (const paragraph of paragraphs) {
      if (!paragraph.trim()) {
        y += lineHeight * 0.45;
        continue;
      }
      const words = paragraph.split(/\s+/);
      let line = '';
      for (const word of words) {
        const test = line ? `${line} ${word}` : word;
        if (ctx.measureText(test).width > maxWidth && line) {
          if (y > canvasH - 64 * scale) nextPage();
          ctx.fillText(line, margin, y);
          y += lineHeight;
          line = word;
        } else {
          line = test;
        }
      }
      if (line) {
        if (y > canvasH - 64 * scale) nextPage();
        ctx.fillText(line, margin, y);
        y += lineHeight;
      }
    }
  };

  drawWrapped(
    docTitle,
    `700 ${17 * scale}px "Plus Jakarta Sans", "Noto Sans Tamil", sans-serif`,
    '#172554',
    24 * scale
  );
  drawWrapped(
    subtitle,
    `500 ${10.5 * scale}px "DM Sans", "Noto Sans Tamil", sans-serif`,
    '#2563EB',
    18 * scale
  );
  y += 10 * scale;

  for (const sec of sections) {
    if (y > canvasH - 100 * scale) nextPage();
    y += 8 * scale;
    drawWrapped(
      sec.heading,
      `700 ${13 * scale}px "Plus Jakarta Sans", "Noto Sans Tamil", sans-serif`,
      '#2563EB',
      20 * scale
    );
    y += 4 * scale;
    for (const line of sec.lines) {
      drawWrapped(
        line,
        `400 ${11 * scale}px "DM Sans", "Noto Sans Tamil", sans-serif`,
        '#172554',
        17 * scale
      );
      y += 4 * scale;
    }
  }

  doc.addImage(canvas.toDataURL('image/png'), 'PNG', 0, 0, pageWidth, pageHeight);
  doc.save(outputFilename);
}

function renderAsciiSectionsToPdf(
  docTitle: string,
  subtitle: string,
  sections: { heading: string; lines: string[] }[],
  outputFilename: string
) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 48;
  const maxWidth = pageWidth - margin * 2;

  const drawHeader = (pageNum: number) => {
    doc.setFillColor(23, 37, 84); // #172554
    doc.rect(0, 0, pageWidth, 64, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(16);
    doc.text('JOSH PDF', margin, 28);
    doc.setTextColor(147, 197, 253);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.text(
      'Upload. Understand. Learn Faster.  |  Free AI-Powered PDF Summarizer',
      margin,
      46
    );

    doc.setTextColor(100, 116, 139);
    doc.setFontSize(8.5);
    doc.text(`Generated by JOSH PDF  |  Page ${pageNum}`, margin, pageHeight - 24);
  };

  let pageNum = 1;
  drawHeader(pageNum);
  let y = 96;

  const ensureSpace = (needed: number) => {
    if (y + needed > pageHeight - 48) {
      doc.addPage();
      pageNum += 1;
      drawHeader(pageNum);
      y = 92;
    }
  };

  doc.setTextColor(23, 37, 84);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  const titleLines = doc.splitTextToSize(docTitle, maxWidth);
  doc.text(titleLines, margin, y);
  y += titleLines.length * 19 + 4;

  doc.setTextColor(37, 99, 235);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(subtitle, margin, y);
  y += 22;

  for (const sec of sections) {
    ensureSpace(34);
    doc.setTextColor(37, 99, 235);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.text(sec.heading, margin, y);
    y += 18;

    doc.setTextColor(23, 37, 84);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10.5);
    for (const rawLine of sec.lines) {
      const wrapped = doc.splitTextToSize(cleanPlainText(rawLine), maxWidth);
      ensureSpace(wrapped.length * 14 + 6);
      doc.text(wrapped, margin, y);
      y += wrapped.length * 14 + 5;
    }
    y += 8;
  }

  doc.save(outputFilename);
}

function smartExportPdf(
  docTitle: string,
  subtitle: string,
  sections: { heading: string; lines: string[] }[],
  outputFilename: string
) {
  const combined =
    docTitle +
    subtitle +
    sections.map((s) => s.heading + s.lines.join(' ')).join(' ');
  if (containsNonAscii(combined)) {
    void renderUnicodeLinesToPdf(docTitle, subtitle, sections, outputFilename);
  } else {
    renderAsciiSectionsToPdf(docTitle, subtitle, sections, outputFilename);
  }
}

export function exportSummaryPdf(
  summary: SummaryResult,
  fileName: string,
  language: AppLanguage
) {
  const baseName = fileName.replace(/\.pdf$/i, '');
  const sections = [
    ...(summary.tldr
      ? [
          {
            heading: language === 'ta' ? 'ஒரே வரியில் (TL;DR)' : 'In One Sentence (TL;DR)',
            lines: [summary.tldr],
          },
        ]
      : []),
    {
      heading: language === 'ta' ? 'முதன்மைச் சுருக்கம் (Chapter Overview)' : 'Chapter Overview',
      lines: [summary.executiveSummary],
    },
    {
      heading: language === 'ta' ? 'முக்கிய புள்ளிகள் (Key Points)' : 'Key Study Points',
      lines: summary.keyPoints.map((pt, i) => `${i + 1}. ${pt}`),
    },
    {
      heading: language === 'ta' ? 'அடிப்படைக் கருத்துகள் (Core Concepts)' : 'Key Terms & Concepts',
      lines: summary.concepts.map(
        (c) => `• ${c.term}: ${c.explanation}${c.example ? ` (Example: ${c.example})` : ''}`
      ),
    },
    ...(summary.formulasAndFacts && summary.formulasAndFacts.length > 0
      ? [
          {
            heading:
              language === 'ta'
                ? 'முக்கிய தகவல்கள் & சூத்திரங்கள்'
                : 'Important Facts, Dates & Formulas',
            lines: summary.formulasAndFacts.map((f) => `• ${f}`),
          },
        ]
      : []),
    {
      heading: language === 'ta' ? 'கற்றல் குறிப்புகள் (Study Takeaways)' : 'Exam & Revision Takeaways',
      lines: summary.studyTakeaways.map((t) => `• ${t}`),
    },
  ];

  smartExportPdf(
    summary.title || baseName,
    `Source: ${fileName}  |  JOSH PDF Study Summary`,
    sections,
    `JOSH-PDF-Summary-${baseName}.pdf`
  );
}

export function exportQuizPdf(
  questions: QuizQuestion[],
  fileName: string,
  language: AppLanguage
) {
  const baseName = fileName.replace(/\.pdf$/i, '');
  const questionLines: string[] = [];
  const answerLines: string[] = [];

  questions.forEach((q, idx) => {
    questionLines.push(`Q${idx + 1}. ${q.question}`);
    q.options.forEach((opt, oIdx) => {
      const label = String.fromCharCode(65 + oIdx);
      questionLines.push(`   ${label}) ${opt}`);
    });
    const correctLetter = String.fromCharCode(65 + q.correctIndex);
    answerLines.push(
      `Q${idx + 1}: ${correctLetter} — ${q.options[q.correctIndex] || ''} (${q.explanation})`
    );
  });

  smartExportPdf(
    `${baseName} — Practice Quiz`,
    `JOSH PDF Practice Assessment (${language === 'ta' ? 'Tamil' : 'English'})`,
    [
      {
        heading: language === 'ta' ? 'கேள்விகள் (Questions)' : 'Questions',
        lines: questionLines,
      },
      {
        heading: language === 'ta' ? 'விடைகளும் விளக்கமும் (Answer Key)' : 'Answer Key & Explanations',
        lines: answerLines,
      },
    ],
    `JOSH-PDF-Quiz-${baseName}.pdf`
  );
}

export function exportQaPdf(
  messages: QaMessage[],
  fileName: string,
  language: AppLanguage
) {
  const baseName = fileName.replace(/\.pdf$/i, '');
  const lines = messages.map(
    (m) => `${m.role === 'user' ? 'Question' : 'JOSH PDF Answer'}: ${m.content}`
  );

  smartExportPdf(
    `${baseName} — Document Q&A`,
    `JOSH PDF Q&A Transcript (${language === 'ta' ? 'Tamil' : 'English'})`,
    [
      {
        heading: language === 'ta' ? 'கேள்வி & பதில் பதிவு' : 'Q&A Transcript',
        lines,
      },
    ],
    `JOSH-PDF-QA-${baseName}.pdf`
  );
}

export function exportMarkdownFile(
  summary: SummaryResult,
  qaHistory: QaMessage[],
  quizQuestions: QuizQuestion[],
  fileName: string
) {
  const baseName = fileName.replace(/\.pdf$/i, '');
  const parts: string[] = [
    `# ${summary.title || baseName}`,
    `> Generated by **JOSH PDF** — *Upload. Understand. Learn Faster.*`,
    '',
    ...(summary.tldr ? ['**TL;DR:** ' + summary.tldr, ''] : []),
    '## Chapter Overview',
    summary.executiveSummary,
    '',
    '## Key Study Points',
    ...summary.keyPoints.map((p) => `- ${p}`),
    '',
    '## Key Terms & Concepts',
    ...summary.concepts.map(
      (c) => `- **${c.term}**: ${c.explanation}${c.example ? ` *(Example: ${c.example})*` : ''}`
    ),
    ...(summary.formulasAndFacts && summary.formulasAndFacts.length > 0
      ? ['', '## Important Facts, Dates & Formulas', ...summary.formulasAndFacts.map((f) => `- ${f}`)]
      : []),
    '',
    '## Exam & Revision Takeaways',
    ...summary.studyTakeaways.map((t) => `- ${t}`),
  ];

  if (qaHistory.length > 0) {
    parts.push('', '## Document Q&A');
    qaHistory.forEach((m) => {
      parts.push(`**${m.role === 'user' ? 'Q' : 'A'}:** ${m.content}`, '');
    });
  }

  if (quizQuestions.length > 0) {
    parts.push('', '## Practice Quiz');
    quizQuestions.forEach((q, idx) => {
      parts.push(`### ${idx + 1}. ${q.question}`);
      q.options.forEach((opt, i) => {
        parts.push(`- ${String.fromCharCode(65 + i)}) ${opt}`);
      });
      parts.push(
        `**Answer:** ${String.fromCharCode(65 + q.correctIndex)} — ${q.explanation}`,
        ''
      );
    });
  }

  const blob = new Blob([parts.join('\n')], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `JOSH-PDF-${baseName}.md`;
  a.click();
  URL.revokeObjectURL(url);
}

export function generateSampleStudyPdf(): {
  fileName: string;
  blob: Blob;
  blobUrl: string;
  sizeBytes: number;
} {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const margin = 48;
  const maxWidth = doc.internal.pageSize.getWidth() - margin * 2;

  doc.setFillColor(23, 37, 84);
  doc.rect(0, 0, doc.internal.pageSize.getWidth(), 72, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text('Photosynthesis & Cellular Respiration', margin, 34);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10.5);
  doc.setTextColor(191, 219, 254);
  doc.text('Sample Study Notes  |  Prepared for JOSH PDF Demonstration', margin, 54);

  let y = 104;
  const addSection = (heading: string, body: string) => {
    doc.setTextColor(37, 99, 235);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12.5);
    doc.text(heading, margin, y);
    y += 18;

    doc.setTextColor(23, 37, 84);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10.5);
    const lines = doc.splitTextToSize(body, maxWidth);
    doc.text(lines, margin, y);
    y += lines.length * 14.5 + 14;
  };

  addSection(
    '1. Overview of Photosynthesis',
    'Photosynthesis is the biochemical process by which green plants, algae, and certain bacteria convert light energy into chemical energy stored in glucose. It takes place primarily within chloroplasts containing the green pigment chlorophyll. The overall balanced equation is: 6 CO2 + 6 H2O + Light Energy -> C6H12O6 + 6 O2.'
  );
  addSection(
    '2. Two Major Stages: Light Reactions & Calvin Cycle',
    'Light-dependent reactions occur on the thylakoid membranes inside chloroplasts. Water molecules are split (photolysis), releasing oxygen gas (O2) and producing ATP and NADPH. The Calvin Cycle (light-independent reactions) occurs in the stroma, where the enzyme RuBisCO fixes carbon dioxide into 3-carbon sugars using ATP and NADPH.'
  );
  addSection(
    '3. Factors Affecting Rate of Photosynthesis',
    'Three primary environmental limiting factors govern photosynthetic rate: (a) Light intensity increases the rate up to a saturation point; (b) Carbon dioxide concentration elevates carbon fixation until enzymes saturate; (c) Temperature controls enzyme activity, with optimal efficiency around 25-35 degrees Celsius before enzymes denature at high heat.'
  );
  addSection(
    '4. Connection to Cellular Respiration',
    'Cellular respiration is the complementary metabolic pathway occurring in mitochondria where cells break down glucose in the presence of oxygen to release usable ATP energy, carbon dioxide, and water: C6H12O6 + 6 O2 -> 6 CO2 + 6 H2O + ATP. Together, photosynthesis and respiration drive the global carbon and oxygen cycles.'
  );

  const blob = doc.output('blob');
  const blobUrl = URL.createObjectURL(blob);

  return {
    fileName: 'Photosynthesis-Study-Notes.pdf',
    blob,
    blobUrl,
    sizeBytes: blob.size,
  };
}
